"""General-domain pretraining data (M4.1): FineWeb-Edu + Cosmopedia v2.

Everything here is deterministic and framework-free apart from ``pyarrow`` for
reading Parquet (the optional ``data`` dependency):

* ``SOURCES``: the two approved files, pinned to a dataset commit, with the size and
  SHA-256 published by the Hub (LFS oid). ``verify_file`` checks both.
* ``read_texts``: stream one text column out of a Parquet file.
* ``clean_text`` / ``quality_reject``: conservative normalization and a short list of
  obvious-garbage rules (documented in the report).
* ``dedup_documents``: exact (SHA-256) and near-duplicate (MinHash + LSH, from
  ``tinystories``) removal across all sources *before* any split, so a near-duplicate
  cluster can never straddle train and validation.
* ``split_of``: document-hash split (validation, holdout, train).
* ``decontaminate``: word 8-gram overlap with the frozen evaluation suite.
"""

