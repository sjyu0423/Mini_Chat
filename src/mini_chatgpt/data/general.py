SPECIAL_TOKENS = ("<|endoftext|>", "<|user|>", "<|assistant|>", "<|system|>", "<|end|>")


def file_sha256(path: str | Path, chunk: int = 1 << 24) -> str:
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


def verify_file(path: Path, src: Source) -> str:
    """Raise unless ``path`` has the pinned size and SHA-256; returns the hash."""
    if not path.exists():
        raise FileNotFoundError(f"{path} missing; download {src.url}")
    size = path.stat().st_size
    if size != src.size:
        raise RuntimeError(f"{path}: {size} bytes, expected {src.size}")
    digest = file_sha256(path)
    if digest != src.sha256:
        raise RuntimeError(f"{path}: sha256 {digest} != pinned {src.sha256}")
    return digest


def read_texts(path: Path, column: str, batch_rows: int = 8192) -> Iterator[str]:
    """Stream one string column from a Parquet file (other columns are never read)."""
    import pyarrow.parquet as pq  # optional dependency, imported only when needed

    pf = pq.ParquetFile(path)
    for batch in pf.iter_batches(batch_size=batch_rows, columns=[column]):
        for value in batch.column(0).to_pylist():
            if isinstance(value, str):
                yield value


# --------------------------------------------------------------------------- #
# cleaning
# --------------------------------------------------------------------------- #
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")
_TRAILING_WS = re.compile(r"[ \t]+\n")
_MANY_BLANK = re.compile(r"\n{3,}")
_WORDS = re.compile(r"\w+")


def clean_text(text: str) -> str:
    """NFC, Unix newlines, no C0/DEL control characters (tab and newline kept), no
    trailing spaces, at most one blank line in a row, stripped ends."""
    t = unicodedata.normalize("NFC", text)
    t = t.replace("\r\n", "\n").replace("\r", "\n")
    t = _CONTROL.sub("", t)
    t = _TRAILING_WS.sub("\n", t)
    t = _MANY_BLANK.sub("\n\n", t)
    return t.strip()


def quality_reject(text: str) -> str | None:
    """Reason to drop a cleaned document, or None. Deliberately conservative: only
    rules that catch obvious garbage (both sources are already filtered upstream)."""
    if "�" in text:
        return "replacement_character"
    words = _WORDS.findall(text)
    if len(words) < 50:
        return "fewer_than_50_words"
    # Only substantive lines (>= 30 chars) count: short structural lines such as code
    # fences, "* * *" separators and table rules legitimately repeat in good documents.
    lines = [ln.strip() for ln in text.split("\n") if len(ln.strip()) >= 30]
    if lines:
        counts: dict[str, int] = {}
        for ln in lines:
            counts[ln] = counts.get(ln, 0) + 1
        if sum(c for c in counts.values() if c > 1) / len(lines) > 0.3:
            return "duplicate_lines_over_30pct"
    letters = sum(ch.isalpha() for ch in text)
    if letters / len(text) < 0.5:
        return "letters_under_50pct"
    return None


# --------------------------------------------------------------------------- #
# deduplication, split, decontamination
# --------------------------------------------------------------------------- #
@dataclass
class Doc:
    source: str
    text: str
    sha: str = ""

    def __post_init__(self) -> None:
        if not self.sha:
            self.sha = text_sha256(self.text)


@dataclass
class DedupStats:
    input_docs: int = 0
    exact_removed: dict[str, int] = field(default_factory=dict)
    near_pairs: int = 0
    near_removed: dict[str, int] = field(default_factory=dict)
    cross_source_near_pairs: int = 0
    kept: dict[str, int] = field(default_factory=dict)
    examples: list[list[str]] = field(default_factory=list)


def dedup_documents(docs: Sequence[Doc], cfg: MinHashConfig) -> tuple[list[Doc], DedupStats]:
    """Exact then near-duplicate removal over all sources together.

    Order is canonical (by SHA-256), so the survivor of each cluster is the
    document with the smallest hash: independent of file order.
    """
    st = DedupStats(input_docs=len(docs))
    seen: set[str] = set()
    unique: list[Doc] = []
    for d in sorted(docs, key=lambda d: d.sha):
        if d.sha in seen:
            st.exact_removed[d.source] = st.exact_removed.get(d.source, 0) + 1
            continue
        seen.add(d.sha)
        unique.append(d)
    sigs = minhash_signatures([d.text for d in unique], cfg)
    pairs = near_duplicate_pairs(sigs, cfg)
    st.near_pairs = len(pairs)
    parent = list(range(len(unique)))

    def find(i: int) -> int:
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for i, j, _ in pairs:
        if unique[i].source != unique[j].source:
            st.cross_source_near_pairs += 1
        ri, rj = find(i), find(j)
        if ri != rj:
            parent[max(ri, rj)] = min(ri, rj)
    kept: list[Doc] = []
    for k, d in enumerate(unique):
        if find(k) == k:
            kept.append(d)
            st.kept[d.source] = st.kept.get(d.source, 0) + 1
        else:
            st.near_removed[d.source] = st.near_removed.get(d.source, 0) + 1
    for i, j, _ in pairs[:3]:
        st.examples.append([unique[i].text[:160], unique[j].text[:160]])
    return kept, st


def split_of(sha: str) -> str:
    """``int(sha[:8], 16) % 1000``: 0-4 validation, 5-9 holdout, 10-999 train."""
    bucket = int(sha[:8], 16) % 1000
    if bucket < 5:
        return "val"
    if bucket < 10:
        return "holdout"
    return "train"


def eval_ngrams(eval_texts: dict[str, str], n: int = 8) -> dict[tuple[str, ...], set[str]]:
    """Word n-grams of every eval item with at least n words (shorter items are
    too generic to decontaminate and are reported only)."""
    index: dict[tuple[str, ...], set[str]] = {}
    for key, text in eval_texts.items():
        toks = _WORDS.findall(text.lower())
        for i in range(len(toks) - n + 1):
            index.setdefault(tuple(toks[i : i + n]), set()).add(key)
    return index


def contaminating_items(text: str, index: dict[tuple[str, ...], set[str]], n: int = 8) -> set[str]:
    toks = _WORDS.findall(text.lower())
    hits: set[str] = set()
    for i in range(len(toks) - n + 1):
        found = index.get(tuple(toks[i : i + n]))
        if found:
            hits |= found
    return hits


def stats_dict(obj: Any) -> dict[str, Any]:
    from dataclasses import asdict

    return asdict(obj)
