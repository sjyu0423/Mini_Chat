import { useEffect } from "react";
import type { ModelInfo } from "../api";
import { DEFAULT_SETTINGS } from "../settings";
import type { UiSettings } from "../settings";

interface SettingsProps {
  settings: UiSettings;
  onChange: (s: UiSettings) => void;
  limits: { minT: number; maxT: number; minTokens: number; maxTokens: number };
}

export function SettingsPanel({ settings, onChange, limits }: SettingsProps) {
  return (
    <section className="panel" aria-label="Advanced settings">
      <h2>Advanced settings</h2>
      <label className="field">
        <span>
          Temperature <output>{settings.temperature.toFixed(2)}</output>
        </span>
        <input
          type="range"
          aria-label="Temperature"
          min={limits.minT}
          max={limits.maxT}
          step={0.05}
          value={settings.temperature}
          onChange={(e) => onChange({ ...settings, temperature: Number(e.target.value) })}
        />
        <small>Lower is more predictable, higher is more varied (and more often nonsense).</small>
      </label>
      <label className="field">
        <span>
          Max new tokens <output>{settings.maxNewTokens}</output>
        </span>
        <input
          type="range"
          aria-label="Max new tokens"
          min={16}
          max={limits.maxTokens}
          step={8}
          value={settings.maxNewTokens}
          onChange={(e) => onChange({ ...settings, maxNewTokens: Number(e.target.value) })}
        />
        <small>Replies longer than this are cut off and marked as such.</small>
      </label>
      <p className="fixed">
        Fixed: top-k 40, repetition penalty 1.2 (the M5 recommended configuration).
      </p>
      <button type="button" className="link" onClick={() => onChange(DEFAULT_SETTINGS)}>
        Reset to defaults
      </button>
    </section>
  );
}

export function AboutPanel({ model, onClose }: { model?: ModelInfo; onClose: () => void }) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && onClose();
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);
  return (
    <div className="overlay" role="dialog" aria-modal="true" aria-labelledby="about-title" onClick={onClose}>
      <div className="dialog" onClick={(e) => e.stopPropagation()}>
        <h2 id="about-title">About this model</h2>
        <ul>
          <li>
            About <strong>14 million parameters</strong>
            {model ? ` (${model.parameters.toLocaleString("en-US")})` : ""}: a custom GPT-style
            Transformer ({model ? `${model.n_layer} layers, ${model.n_head} heads, width ${model.n_embd}` : "6 layers"},
            512-token context) and its own byte-level BPE tokenizer.
          </li>
          <li>
            <strong>Pretrained from random initialization</strong> on about 157 million tokens of
            educational web text and textbook-style text. No pretrained weights were used.
          </li>
          <li>
            <strong>Fine-tuned for basic conversational formatting</strong> on human-written
            conversations (OASST2 and Dolly-15k): it learned to answer in turn and to stop.
          </li>
          <li>
            <strong>No external model API.</strong> Every reply is generated by this model, running
            locally on Apple Silicon{model ? ` (device: ${model.device})` : ""}. Nothing is sent to
            the internet.
          </li>
          <li>
            <strong>Known limitations:</strong> very little factual knowledge (most factual answers
            are wrong), shallow reasoning, weak memory of earlier turns, sometimes repetitive, English
            only. It is a learning project, not an assistant.
          </li>
        </ul>
        <button type="button" className="primary" onClick={onClose} autoFocus>
          Close
        </button>
      </div>
    </div>
  );
}
